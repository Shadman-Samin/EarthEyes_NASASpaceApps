test("mobile navigation supports Escape, route changes and the skip link", async ({ page }) => {
  await page.setViewportSize({ width: 360, height: 800 })
  await page.goto("/")
  const menu = page.getByRole("button", { name: "Open navigation", exact: true })
  await menu.focus()
  await page.keyboard.press("Enter")
  const navigation = page.getByRole("navigation", { name: "Mobile navigation" })
  await expect(navigation.getByRole("link", { name: "Home", exact: true })).toHaveAttribute("aria-current", "page")
  await navigation.getByRole("link", { name: "Home", exact: true }).focus()
  await page.keyboard.press("Escape")
  await expect(menu).toBeFocused()
  await expect(navigation).toHaveCount(0)
  await page.keyboard.press("Enter")
  await navigation.getByRole("link", { name: "About", exact: true }).focus()
  await page.keyboard.press("Enter")
  await expect(page).toHaveURL(/\/about$/)
  await expect(navigation).toHaveCount(0)
  const skip = page.getByRole("link", { name: "Skip to main content" })
  await skip.focus()
  await page.keyboard.press("Enter")
  await expect(page.locator("#route-content")).toBeFocused()
})

test("GroundLine validates the local simulation and sends no subscription request", async ({ page }) => {
  await page.clock.setFixedTime(new Date("2026-11-12T12:00:00Z"))
  await page.goto("/groundline")
  await expect(page.getByRole("note", { name: "GroundLine demonstration" })).toContainText("No messages are sent")
  await page.getByRole("tab", { name: "Subscription demo" }).click()
  const mutations: string[] = []
  page.on("request", (request) => { if (["POST", "PUT", "PATCH", "DELETE"].includes(request.method())) mutations.push(request.url()) })
  const storedBefore = await page.evaluate(() => JSON.stringify(localStorage))
  const phone = page.getByRole("textbox", { name: "Phone number / E.164" })
  await phone.fill("+15555550123")
  await page.getByRole("button", { name: "Try verification" }).click()
  await expect(page.getByRole("textbox", { name: "Demo verification code" })).toHaveCount(0)
  await page.getByRole("checkbox").check()
  await phone.fill("123")
  await page.getByRole("button", { name: "Try verification" }).click()
  await expect(phone).toHaveAttribute("aria-invalid", "true")
  await expect(phone).toBeFocused()
  await phone.fill("+15555550123")
  await page.getByRole("combobox", { name: "Language" }).selectOption("en")
  await page.getByRole("radio", { name: "Voice", exact: true }).check()
  await page.getByRole("button", { name: "Try verification" }).click()
  const code = page.getByRole("textbox", { name: "Demo verification code" })
  await expect(code).toBeFocused()
  await code.fill("12345")
  await page.getByRole("button", { name: "Confirm demo code" }).click()
  await expect(page.getByText("Demo preferences confirmed", { exact: true })).toHaveCount(0)
  await code.fill("123456")
  await page.getByRole("button", { name: "Confirm demo code" }).click()
  await expect(page.getByText("Demo preferences confirmed", { exact: true })).toBeVisible()
  await page.getByRole("button", { name: "Unsubscribe demo" }).click()
  await expect(page.getByRole("button", { name: "Try verification" })).toBeVisible()
  expect(mutations).toEqual([])
  expect(await page.evaluate(() => JSON.stringify(localStorage))).toBe(storedBefore)
})

test("Home background video is short, muted, non-interactive and respects reduced motion", async ({ page }, testInfo) => {
  test.skip(testInfo.project.name === "firefox", "Desktop and mobile video checks")
  await page.goto("/")
  const video = page.locator(".landing-hero video")
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.duration)).toBeCloseTo(8, 1)
  await expect.poll(() => video.evaluate((element: HTMLVideoElement) => element.currentTime)).toBeGreaterThan(0)
  expect(await video.evaluate((element: HTMLVideoElement) => element.muted && element.loop && element.playsInline)).toBe(true)
  await expect(page.getByRole("button", { name: "Pause background video" })).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath("home-video.png") })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await expect(video).toHaveCount(0)
  await expect(page.locator(".landing-hero__media img")).toBeVisible()
  await expect(page.getByRole("button", { name: "Ask Argus evidence guide" })).toHaveCount(0)
})

test("editorial touch targets and reduced motion remain usable on mobile", async ({ page }, testInfo) => {
  test.skip(testInfo.project.name !== "mobile", "Canonical mobile target audit")
  await page.emulateMedia({ reducedMotion: "reduce" })
  for (const path of ["/", "/methodology", "/data-sources", "/groundline", "/about"]) {
    await page.goto(path)
    await expect(page.getByRole("heading", { level: 1 })).toBeVisible()
    await expect(page.locator(".skeleton")).toHaveCount(0)
    await expect(page.locator("html")).toHaveCSS("scroll-behavior", "auto")
    const smallTargets = await page.locator("main a, main button, main summary").evaluateAll((elements) => elements.filter((element) => {
      const rect = element.getBoundingClientRect()
      return rect.width > 0 && rect.height > 0 && (rect.height < 44 || rect.width < 44)
    }).map((element) => element.textContent))
    expect(smallTargets, `Small targets at ${path}`).toEqual([])
  }
})
